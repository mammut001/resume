const fs = require("node:fs");
const path = require("node:path");

const resume = require("../src/data/resume-content.json");

const outputPath = path.join(__dirname, "..", "typst", "resume.typ");

const stripProtocol = (value = "") => value.replace(/^https?:\/\//, "").replace(/\/$/, "");

const escapeTypstString = (value = "") =>
  String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

const escapeTypstInline = (value = "") =>
  String(value)
    .replace(/\\/g, "\\\\")
    .replace(/#/g, "\\#")
    .replace(/\$/g, "\\$")
    .replace(/\*/g, "\\*")
    .replace(/_/g, "\\_")
    .replace(/\[/g, "\\[")
    .replace(/\]/g, "\\]");

const typstString = (value = "") => `"${escapeTypstString(value)}"`;

const normalizeWhitespace = (value = "") => value.replace(/\s+/g, " ").trim();

const splitSentences = (value = "") =>
  normalizeWhitespace(value)
    .split(/(?<=[.!?])\s+/)
    .map((sentence) => escapeTypstInline(sentence.trim()))
    .filter(Boolean);

const renderBulletList = (items) => items.map((item) => `- ${item}`).join("\n");

const renderDates = (start, end) => {
  if (start && end) {
    return `dates-helper(start-date: ${typstString(start)}, end-date: ${typstString(end)})`;
  }

  if (start) {
    return typstString(start);
  }

  return typstString("");
};

const findSocial = (name) =>
  resume.contact.social.find((item) => item.name === name)?.url ?? "";

const github = stripProtocol(findSocial("GitHub"));
const linkedin = stripProtocol(findSocial("LinkedIn"));
const personalSite = stripProtocol(resume.personalWebsiteUrl);
const showPersonalSite = personalSite && personalSite !== github;

const renderEducation = () =>
  resume.education
    .slice()
    .reverse()
    .map(
      (entry) => `#edu(\n  institution: ${typstString(entry.school)},\n  location: ${typstString(
        resume.location,
      )},\n  dates: ${renderDates(entry.start, entry.end)},\n  degree: ${typstString(entry.degree)},\n)`,
    )
    .join("\n\n");

const renderWork = () =>
  resume.work
    .slice()
    .reverse()
    .map((entry) => {
      const bullets = splitSentences(entry.description);

      return `#work(\n  title: ${typstString(entry.title)},\n  location: ${typstString(
        resume.location,
      )},\n  company: ${typstString(entry.company)},\n  dates: ${renderDates(entry.start, entry.end)},\n)\n${renderBulletList(bullets)}`;
    })
    .join("\n\n");

const renderProjects = () =>
  resume.projects
    .filter((entry) => entry.status === 1)
    .slice()
    .reverse()
    .map((entry) => {
      const description = splitSentences(entry.description)[0] ?? escapeTypstInline(entry.description);
      const urlLine = entry.link?.href ? `\n  url: ${typstString(stripProtocol(entry.link.href))},` : "";

      return `#project(\n  name: ${typstString(entry.title)},${urlLine}\n)\n- ${description}`;
    })
    .join("\n\n");

const renderResearch = () =>
  resume.research
    .slice()
    .reverse()
    .map((entry) => {
      const bullets = splitSentences(entry.description);

      return `#extracurriculars(\n  activity: ${typstString(entry.title)},\n  dates: ${renderDates(
        entry.start,
        entry.end,
      )},\n)\n${renderBulletList(bullets)}`;
    })
    .join("\n\n");

const skillGroups = [
  {
    label: "Languages",
    values: ["TypeScript", "JavaScript", "Python", "Java", "C++", "Swift", "Rust", "HTML", "CSS", "Bash"],
  },
  {
    label: "Frameworks & Data",
    values: ["NextJS", "TailwindCSS", "Flask", "Tauri v2", "SQLite", "MongoDB", "JQuery"],
  },
  {
    label: "Testing & Delivery",
    values: ["PyTest", "GTest", "SeleniumGrid", "Jenkins", "Docker", "Vagrant"],
  },
  {
    label: "Tools & Platforms",
    values: ["GitHub", "Jira", "Confluence", "Linux", "AWS", "OpenStack", "IntelliJ", "PostMan", "Windows10", "Visual Studio", "Typst", "Mermaid", "Object-Oriented Programming"],
  },
];

const renderSkills = () => {
  const groupedValues = new Set();
  const lines = skillGroups
    .map(({ label, values }) => {
      const presentValues = values.filter((value) => resume.skills.includes(value));

      presentValues.forEach((value) => groupedValues.add(value));

      if (presentValues.length === 0) {
        return null;
      }

      return `- *${label}*: ${escapeTypstInline(presentValues.join(", "))}`;
    })
    .filter(Boolean);

  const remaining = resume.skills.filter((value) => !groupedValues.has(value));

  if (remaining.length > 0) {
    lines.push(`- *Additional*: ${escapeTypstInline(remaining.join(", "))}`);
  }

  return lines.join("\n");
};

const lines = [
  "// Generated from src/data/resume-content.json by scripts/generate-resume-typst.cjs.",
  "// Do not edit this file by hand.",
  '#import "@preview/basic-resume:0.2.9": *',
  "",
  `#let name = ${typstString(resume.name)}`,
  `#let location = ${typstString(resume.location)}`,
  `#let email = ${typstString(resume.contact.email)}`,
  `#let github = ${typstString(github)}`,
  `#let linkedin = ${typstString(linkedin)}`,
  "",
  "#show: resume.with(",
  "  author: name,",
  "  location: location,",
  "  email: email,",
  "  github: github,",
  "  linkedin: linkedin,",
  ...(showPersonalSite ? [`  personal-site: ${typstString(personalSite)},`] : []),
  '  accent-color: "#166534",',
  '  font: "New Computer Modern",',
  '  paper: "us-letter",',
  "  author-position: left,",
  "  personal-info-position: left,",
  ")",
  "",
  "== Summary",
  "",
  escapeTypstInline(resume.summary),
  "",
  "== Education",
  "",
  renderEducation(),
  "",
  "== Work Experience",
  "",
  renderWork(),
  "",
  "== Projects",
  "",
  renderProjects(),
  "",
  "== Research",
  "",
  renderResearch(),
  "",
  "== Skills",
  renderSkills(),
  "",
];

fs.writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");

console.log(`Generated ${path.relative(process.cwd(), outputPath)}`);